// Deterministic text-to-path generator for the LUMAGRID wordmark and horizontal lockup (D-08).
// Reads the static Orbitron 700 latin woff (opentype.js 2.0.0 cannot decompress woff2), outlines
// the text and writes brand/wordmark.svg and brand/lockup.svg. No timestamps, no random ids:
// running it twice yields byte-identical files. Orbitron is OFL-1.1; see NOTICE.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
process.chdir(root);

const FONT_FILE = 'node_modules/@fontsource/orbitron/files/orbitron-latin-700-normal.woff';
const TEXT = 'LUMAGRID';
const FONT_SIZE = 64;
const FILL = '#E6EDF3';
const LOCKUP_HEIGHT = 64;
const LOCKUP_GAP = 16;
const LOCKUP_CAP_HEIGHT = 24;

const buf = readFileSync(FONT_FILE);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

// Measure at the origin, then re-outline shifted so the box starts exactly at 0,0.
const box = font.getPath(TEXT, 0, 0, FONT_SIZE).getBoundingBox();
const path = font.getPath(TEXT, -box.x1, -box.y1, FONT_SIZE);
const d = path.toPathData(2);
const width = Math.ceil(box.x2 - box.x1);
const height = Math.ceil(box.y2 - box.y1);

const provenance = `<!-- Generated by scripts/brand/wordmark.mjs from ${FONT_FILE.split('/').pop()} (Orbitron 700, OFL-1.1). Do not edit by hand. -->`;

const wordmark = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}" role="img">
  ${provenance}
  <title>Lumagrid</title>
  <path fill="${FILL}" d="${d}"/>
</svg>
`;

// Lockup: the mark's shapes at the origin, a 16 unit gap, then the wordmark scaled to a 24 unit cap height.
const markSvg = readFileSync('brand/mark.svg', 'utf8');
const markBody = markSvg.slice(markSvg.indexOf('</title>') + '</title>'.length, markSvg.lastIndexOf('</svg>')).trim();
const scale = LOCKUP_CAP_HEIGHT / (box.y2 - box.y1);
const scaleText = scale.toFixed(4);
const textX = 64 + LOCKUP_GAP;
const textY = LOCKUP_HEIGHT / 2 - LOCKUP_CAP_HEIGHT / 2;
const lockupWidth = Math.ceil(textX + (box.x2 - box.x1) * scale);

const lockup = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${lockupWidth} ${LOCKUP_HEIGHT}" width="${lockupWidth}" height="${LOCKUP_HEIGHT}" role="img">
  ${provenance}
  <title>Lumagrid</title>
  <g>
    ${markBody.replace(/\n/g, '\n    ')}
  </g>
  <g transform="translate(${textX} ${textY}) scale(${scaleText})">
    <path fill="${FILL}" d="${d}"/>
  </g>
</svg>
`;

writeFileSync('brand/wordmark.svg', wordmark);
writeFileSync('brand/lockup.svg', lockup);
console.log(`wordmark.svg ${width}x${height}, lockup.svg ${lockupWidth}x${LOCKUP_HEIGHT} (scale ${scaleText})`);
